async function send(url: string, method: string, body?: unknown): Promise<boolean> {
  try {
    const res = await fetch(url, { method, headers: { "Content-Type": "application/json" }, body: body ? JSON.stringify(body) : undefined });
    return res.ok;
  } catch {
    return false;
  }
}

function useToast() {
  const [msg, setMsg] = useState<string | null>(null);
  const show = (m: string) => { setMsg(m); setTimeout(() => setMsg(null), 2600); };
  return { node: msg ? <div className="toast" role="status">{msg}</div> : null, show };
}

export function ConfirmDialog({ title, children, confirmLabel, danger, onConfirm, onCancel, busy }: {
  title: string; children?: ReactNode; confirmLabel: string; danger?: boolean; busy?: boolean; onConfirm: () => void; onCancel: () => void;
}) {
  return (
    <div className="overlay center" onMouseDown={onCancel}>
      <div className="dialog" role="dialog" aria-modal="true" aria-label={title} onMouseDown={(e) => e.stopPropagation()} onKeyDown={(e) => e.key === "Escape" && onCancel()}>
        <h2>{title}</h2>
        {children}
        <div className="foot">
          <button className="btn" onClick={onCancel}>Cancel</button>
          <button className={`btn ${danger ? "" : "primary"}`} style={danger ? { background: "var(--danger)", color: "#fff", borderColor: "var(--danger)" } : undefined} disabled={busy} onClick={onConfirm}>{confirmLabel}</button>
        </div>
      </div>
    </div>
  );
}

const FLOW = ["AI generated", "Pending review", "Approve / Reject", "Execute", "Completed"];
const flowIndex = (s: Approval["status"]) => (s === "pending" ? 1 : s === "approved" ? 3 : s === "executed" ? 4 : 2);
/** Content approvals record a decision only: nothing is executed or published, so the strip stops at the decision. */
const CONTENT_FLOW = ["AI generated", "Pending review", "Approved / Rejected"];
const contentFlowIndex = (s: Approval["status"]) => (s === "pending" ? 1 : 2);

export function ApprovalQueue({ initial, compact }: { initial: Approval[]; compact?: boolean }) {
  const [items, setItems] = useState(initial);
  const [dialog, setDialog] = useState<{ kind: "edit" | "reject"; item: Approval } | null>(null);
  const [text, setText] = useState({ title: "", preview: "", note: "" });
  const [busy, setBusy] = useState(false);
  const toast = useToast();
  const router = useRouter();

  const patch = (id: string, p: Partial<Approval>) => setItems((xs) => xs.map((x) => (x.id === id ? { ...x, ...p } : x)));

  async function act(item: Approval, action: "approve" | "reject" | "edit", body?: unknown, optimistic?: Partial<Approval>, msg?: string) {
    setBusy(true);
    const ok = await send(`/api/approvals/${item.id}/${action}`, "POST", body);
    setBusy(false);
    if (!ok) return toast.show("That didn’t go through. Please try again.");
    if (optimistic) patch(item.id, optimistic);
    toast.show(msg ?? "Done");
    setDialog(null);
    router.refresh();
  }

  if (!items.length) return <EmptyState title="Nothing awaiting approval" hint="You’re all caught up. New AI drafts will appear here." />;

  return (
    <div className="stack" style={{ gap: 16 }}>
      {items.map((a) => (
        <article key={a.id} className={`card approval ${a.status !== "pending" ? "done" : ""}`} aria-label={a.title}>
          {!compact && <Thumb tone={a.tone} size="lg" />}
          <div style={{ gridColumn: compact ? "1 / -1" : undefined }}>
            <div className="top">
              <div>
                <div className="eyebrow">{a.type}</div>
                <h3>{a.title}</h3>
                <div className="muted" style={{ fontSize: 12.5, marginTop: 2 }}>Generated by {AGENT_NAMES[a.generatedBy]} · {a.created}</div>
              </div>
              <StatusBadge status={a.status === "approved" ? "approved" : a.status} />
            </div>
            {a.meta && (
              <div className="row" style={{ flexWrap: "wrap", gap: 8, margin: "8px 0" }}>
                <span className="badge info">AI-generated draft</span>
                <span className={`badge ${a.meta.isSample ? "champagne" : "plain"}`}>{a.meta.isSample ? "SAMPLE data · not client-verified" : "Client record"}</span>
                <span className="badge plain">Not published</span>
                {a.meta.kind === "b2c_followup" && <span className="badge danger">Consent not recorded — verify permission before contacting.</span>}
              </div>
            )}
            <p className="preview" style={a.meta ? { whiteSpace: "pre-wrap" } : undefined}>{a.preview}</p>
            {!compact && (
              <div className="flow" style={{ marginBottom: 14 }} aria-label="Approval workflow">
                {(a.type === "Content" ? CONTENT_FLOW : FLOW).map((f, i) => {
                  const on = i === (a.type === "Content" ? contentFlowIndex(a.status) : flowIndex(a.status));
                  return <span key={f} className={on ? "on" : ""} aria-current={on ? "step" : undefined}>{f}</span>;
                })}
              </div>
            )}
            {a.status === "pending" ? (
              <>
              <p className="muted" style={{ fontSize: 12, margin: "0 0 8px" }}>Simulated demo actions: nothing is sent, published or saved to any business record.</p>
              <div className="actions">
                <button className="btn" onClick={() => { setText({ title: a.title, preview: a.preview, note: "" }); setDialog({ kind: "edit", item: a }); }}><Pencil size={14} /> Edit</button>
                <button className="btn danger" onClick={() => { setText((t) => ({ ...t, note: "" })); setDialog({ kind: "reject", item: a }); }}><X size={14} /> Reject (demo)</button>
                <button className="btn primary" disabled={busy} onClick={() => act(a, "approve", {}, { status: "approved" }, `Approved (demo) “${a.title}”`)}><Check size={14} /> Approve (demo)</button>
              </div>
              </>
            ) : (
              <p className="muted" style={{ fontSize: 12.5 }}>{a.status === "rejected" ? "Rejected (demo) — simulated. Nothing was sent or saved." : (a.meta ? "Approved (demo) — simulated. Nothing is published or posted to any platform." : "Approved (demo) — simulated. Nothing is sent or published.")}</p>
            )}
          </div>
        </article>
      ))}

      {dialog?.kind === "edit" && (
        <ConfirmDialog title="Edit before approving" confirmLabel="Save changes" busy={busy} onCancel={() => setDialog(null)}
          onConfirm={() => act(dialog.item, "edit", { title: text.title, preview: text.preview }, { title: text.title, preview: text.preview }, "Changes saved (demo)")}>
          <div className="field"><label htmlFor="ed-title">Title</label><input id="ed-title" value={text.title} maxLength={200} onChange={(e) => setText({ ...text, title: e.target.value })} /></div>
          <div className="field"><label htmlFor="ed-body">Content</label><textarea id="ed-body" value={text.preview} maxLength={MAX_PREVIEW_LENGTH} onChange={(e) => setText({ ...text, preview: e.target.value })} /></div>
        </ConfirmDialog>
      )}
      {dialog?.kind === "reject" && (
        <ConfirmDialog title="Reject this draft?" confirmLabel="Reject (demo)" danger busy={busy} onCancel={() => setDialog(null)}
          onConfirm={() => act(dialog.item, "reject", { note: text.note || undefined }, { status: "rejected" }, "Rejected (demo)")}>
          <p className="muted" style={{ marginBottom: 12 }}>Simulated demo action: nothing is sent, published or saved to any business record. It is visible only in your own demo session.</p>
          <div className="field"><label htmlFor="rej">Reason (optional)</label><textarea id="rej" value={text.note} maxLength={500} onChange={(e) => setText({ ...text, note: e.target.value })} /></div>
        </ConfirmDialog>
      )}
      {toast.node}
    </div>
  );
}

const ASSIGNEES = ["Anika", "Dev", "Meera"];

/** `live`: a real organisation's tasks. Assignees are not stored yet, so the demo's name picker is replaced by plain text rather than offering a change that would not be saved. */
export function TaskList({ initial, live = false }: { initial: Task[]; live?: boolean }) {
  const [tasks, setTasks] = useState(initial);
  const toast = useToast();

  async function update(id: string, patch: Partial<Task>, msg: string) {
    const prev = tasks;
    setTasks((ts) => ts.map((t) => (t.id === id ? { ...t, ...patch } : t)));
    const ok = await send(`/api/tasks/${id}`, "PATCH", patch);
    if (!ok) { setTasks(prev); toast.show("Couldn’t update the task."); } else toast.show(msg);
  }

  if (!tasks.length) return <EmptyState title="No tasks" hint="Follow-ups created by agents will show up here." />;
  return (
    <div className="card flush">
      <div className="table-wrap">
        <table className="data stack-sm">
          <thead><tr>{["Task", "Source", "Due", "Priority", "Assignee", "Status", "Actions"].map((h) => <th key={h} scope="col">{h}</th>)}</tr></thead>
          <tbody>
            {tasks.map((t) => (
              <tr key={t.id} style={t.status === "done" ? { opacity: 0.55 } : undefined}>
                <td className="primary" style={t.status === "done" ? { textDecoration: "line-through" } : undefined}>{t.title}</td>
                <td data-label="Source" className="muted">{t.source}</td>
                <td data-label="Due">{t.due}</td>
                <td data-label="Priority"><StatusBadge status={t.priority} /></td>
                <td data-label="Assignee">
                  {live ? t.assignee : (
                    <select aria-label={`Reassign “${t.title}”`} value={t.assignee} onChange={(e) => update(t.id, { assignee: e.target.value }, `Reassigned to ${e.target.value}`)} style={{ font: "inherit", border: 0, background: "transparent" }}>
                      {ASSIGNEES.map((a) => <option key={a}>{a}</option>)}
                    </select>
                  )}
                </td>
                <td data-label="Status"><StatusBadge status={t.status} /></td>
                <td>
                  <div className="row wrap" style={{ gap: 6 }}>
                    <button className="btn sm" disabled={t.status === "done"} onClick={() => update(t.id, { status: "done" }, "Marked complete")}>Complete</button>
                    <button className="btn sm" disabled={t.status !== "open"} onClick={() => update(t.id, { status: "postponed", due: "Postponed +1 day" }, "Postponed by a day")}>Postpone</button>
                    <Link className="btn sm ghost" href={t.href}>Open <ChevronRight size={12} /></Link>
                  </div>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      {toast.node}
    </div>
  );
}

export function PipelineBoard({ initial }: { initial: Deal[] }) {
  const [deals, setDeals] = useState(initial);
  const [over, setOver] = useState<PipelineStage | null>(null);
  const toast = useToast();

  async function move(id: string, stage: PipelineStage) {
    const prev = deals;
    if (prev.find((d) => d.id === id)?.stage === stage) return;
    setDeals((ds) => ds.map((d) => (d.id === id ? { ...d, stage, updated: "just now" } : d)));
    const ok = await send(`/api/pipeline/${id}`, "PATCH", { stage });
    if (!ok) { setDeals(prev); toast.show("Couldn’t move the card."); } else toast.show(`Moved to ${STAGE_LABELS[stage]}`);
  }

  return (
    <>
      <div className="board" aria-label="Sales pipeline board">
        {STAGES.map((s) => {
          const col = deals.filter((d) => d.stage === s);
          return (
            <div key={s} className={`col ${over === s ? "over" : ""}`}
              onDragOver={(e) => { e.preventDefault(); setOver(s); }} onDragLeave={() => setOver(null)}
              onDrop={(e) => { e.preventDefault(); setOver(null); move(e.dataTransfer.getData("text/plain"), s); }}>
              <h3><span>{STAGE_LABELS[s]}</span><span className="num">{col.length}</span></h3>
              {col.map((d) => (
                <div key={d.id} className="deal" draggable onDragStart={(e) => e.dataTransfer.setData("text/plain", d.id)}>
                  <Link href={`/retailers/${d.retailerId}`}><b>{d.business}</b></Link>
                  <span className="muted" style={{ fontSize: 12 }}>{d.location}</span>
                  <div className="row" style={{ justifyContent: "space-between", marginTop: 8, fontSize: 12 }}>
                    <span className="row" style={{ gap: 6 }}><Avatar name={d.owner} size="sm" /><span className="muted">{d.updated}</span></span>
                    <span className="num">{d.score}</span>
                  </div>
                  <label className="sr-only" htmlFor={`mv-${d.id}`}>Move {d.business} to stage</label>
                  <select id={`mv-${d.id}`} className="sr-only" value={d.stage} onChange={(e) => move(d.id, e.target.value as PipelineStage)}>
                    {STAGES.map((x) => <option key={x} value={x}>{STAGE_LABELS[x]}</option>)}
                  </select>
                </div>
              ))}
              {col.length === 0 && <p className="muted" style={{ fontSize: 12, padding: 6 }}>Drop a lead here</p>}
            </div>
          );
        })}
      </div>
      {toast.node}
    </>
  );
}

export function RangeSelect() {
  const router = useRouter();
  const pathname = usePathname();
  const params = useSearchParams();
  const current = params.get("range") ?? "7d";
  const opts = [["today", "Today"], ["7d", "7 Days"], ["30d", "30 Days"], ["90d", "90 Days"], ["custom", "Custom"]];
  return (
    <div className="seg" role="group" aria-label="Date range">
      {opts.map(([id, label]) => (
        <button key={id} aria-pressed={current === id} onClick={() => router.push(`${pathname}?range=${id}`)}>{label}</button>
      ))}
    </div>
  );
}
